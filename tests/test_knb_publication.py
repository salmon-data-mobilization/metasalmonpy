# --- exact planner parity with R ----------------------------------------------------


class KnbPlannerParityTests(unittest.TestCase):
    """Drive the planner from R's own member table and match it exactly.

    The archive ZIP and the EML document are byte-different by construction
    (PARITY.md 4, 15, 17), so the end-to-end Python plan cannot reproduce R's
    hashes. Feeding R's member table isolates every algorithm that *is*
    byte-exact: the resource-map PID, the ORE graph, the fingerprint payload
    encoding, the fingerprint itself, and the manifest JSON.
    """

    def setUp(self):
        self.manifest = _r_manifest()
        self.members = [
            obj
            for obj in self.manifest["objects"]
            if obj["role"] != "resource_map"
        ]

    def test_resource_map_pid_matches_r(self):
        self.assertEqual(
            knb._resource_map_pid(
                self.manifest["package_id"], "2026-01-01", self.members
            ),
            self.manifest["resource_map_pid"],
        )

    def test_ore_document_matches_r(self):
        ore = knb._build_ore(
            self.manifest["resource_map_pid"],
            self.manifest["package_id"],
            "2026-01-01",
            self.members,
        )
        knb._validate_ore(ore, self.manifest["resource_map_pid"], self.members)
        self.assertEqual(
            _canonical_bytes(knb._xml_bytes(ore)),
            _canonical_file(os.path.join(_R_DIR, "public", "resource-map.rdf")),
        )

    def test_ore_validation_rejects_a_tampered_graph(self):
        ore = knb._build_ore(
            self.manifest["resource_map_pid"],
            self.manifest["package_id"],
            "2026-01-01",
            self.members,
        )
        for node in knb._find_all_local(ore, "aggregates"):
            node.set("rdf:resource", knb._resolve_url("urn:uuid:not-planned"))
            break
        with self.assertRaises(ValueError):
            knb._validate_ore(
                ore, self.manifest["resource_map_pid"], self.members
            )

    def test_fingerprint_payload_bytes_match_r(self):
        # plan_sha256 hashes these exact bytes; a JSON-encoding difference
        # would silently invalidate every reviewed manifest.
        with open(
            os.path.join(_R_DIR, "public", "plan-fingerprint-payload.json"), "rb"
        ) as handle:
            payload = handle.read()
        self.assertEqual(knb._json_bytes(json.loads(payload)), payload)
        self.assertEqual(
            knb._sha256_raw(payload), self.manifest["plan_sha256"]
        )

    def test_plan_fingerprint_matches_r(self):
        self.assertEqual(
            knb._plan_fingerprint(self.manifest), self.manifest["plan_sha256"]
        )
        self.assertEqual(
            knb._manifest_fingerprint(self.manifest),
            self.manifest["plan_sha256"],
        )

    def test_private_plan_fingerprint_matches_r(self):
        private = _r_manifest("private")
        self.assertEqual(
            knb._plan_fingerprint(private), private["plan_sha256"]
        )
        # Same objects, different access decision: the fingerprint must move.
        self.assertNotEqual(
            private["plan_sha256"], self.manifest["plan_sha256"]
        )

    def test_schema_version_2_fingerprint_matches_r(self):
        with open(
            os.path.join(_R_DIR, "public", "knb-manifest-v2.json"),
            encoding="utf-8",
        ) as handle:
            legacy = json.load(handle)
        self.assertEqual(
            knb._manifest_fingerprint(legacy),
            _expected()["extra"]["manifest_v2_plan_sha256"],
        )
        self.assertEqual(
            knb._manifest_fingerprint(legacy), legacy["plan_sha256"]
        )

    def test_manifest_bytes_match_r(self):
        with open(
            os.path.join(_R_DIR, "public", "knb-manifest.json"), "rb"
        ) as handle:
            payload = handle.read()
        built = knb._manifest(self.manifest, status="dry_run")
        self.assertEqual(knb._json_bytes(built), payload)

    def test_manifest_carries_previous_object_state_and_status(self):
        previous = knb._manifest(self.manifest, status="dry_run")
        previous["status"] = "complete"
        for obj in previous["objects"]:
            obj["state"] = "verified"
        previous["catalog_verified"] = True
        rebuilt = knb._manifest(
            self.manifest, status="dry_run", previous=previous
        )
