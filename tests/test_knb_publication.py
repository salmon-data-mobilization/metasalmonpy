"""
Offline parity tests for KNB/DataONE publication (metasalmon 0.1.7 parity).

Fixtures under ``tests/data/knb/`` were generated by running metasalmon at the
**v0.1.7 tag** (R 4.5.2, zip 3.0.1, datapack 1.4.2, emld 0.5.3 — see
``expected.json["generated_by"]``): two source SDPs, the dry-run manifests,
OAI-ORE resource maps and deterministic SDP ZIP R produced from them, the exact
JSON payload R hashes into ``plan_sha256``, the SystemMetadata documents R
uploads, and a table of pure-helper return values.

**No test touches the network.** Every live-path test injects a fake adapter
through ``set_knb_adapter``, mirroring R's ``metasalmon.knb_adapter`` option;
the dry-run tests install an adapter whose every method raises, which is the
sentinel proving no adapter is constructed on the planning path.

Parity boundaries, and why they are where they are:

* **Byte-exact with R** — the plan fingerprint payload and its SHA-256, the
  recovery manifest JSON, every identifier (resource-map PID, archive PID,
  artifact PIDs), the Solr catalog URL, redaction, and the ORE/SystemMetadata
  documents compared with ``ET.canonicalize``.
* **Contract-level only** — the SDP ZIP (R pins ``zip`` 3.0.1; Python defines
  its own :mod:`zipfile` determinism reference) and the EML document (libxml2
  vs ElementTree). Because those two artifacts' *bytes* differ, so do the
  archive and resource-map object checksums Python computes end to end — which
  is why the exact-parity tests drive the planner from R's own member table
  rather than from a Python-built archive. PARITY.md entries 4, 15, 17.
"""

