def test_writer_is_deterministic_across_input_order(tmp_path):
    rows = load_rows("full-sdp")
    first = make_sdp(tmp_path, "full-sdp", "first")
    second = make_sdp(tmp_path, "full-sdp", "second")
    write_sdp_measurement_decompositions(first, rows)
