def test_statistical_modifier_role_is_accepted_and_method_is_not(tmp_path):
    # sdp-0.3.0 dropped the transitional method role: a decomposition row
    # binds one variable's identity, and a row-varying procedure would pin an
    # arbitrary one. The aggregation identity slot is statistical_modifier.
    rows = era_rows()
    assert "statistical_modifier" in rows["component_role"].tolist()
    assert "method" not in rows["component_role"].tolist()

    legacy = era_rows()
    legacy.loc[4, "component_role"] = "method"
    sdp = make_sdp(tmp_path, "era-sdp")
    with pytest.raises(ValueError, match="component_role must be one of"):
        write_sdp_measurement_decompositions(sdp, legacy)


