"""Measurement-decomposition tests (sdp-0.3.0 shape, S10 chunk A).

Byte-parity fixtures under ``tests/data/decompositions/`` were generated by
running metasalmon's R implementation (``R/measurement-decompositions.R``)
from **main at e02111a** — the v0.3.0 release tree plus the post-0.3.0 fixes
— over the same ``src/`` rows this suite feeds the Python writer:

- ``era-sdp/``        an SDP whose artifact is metasalmon's own six-component
                      test table, including a ``statistical_modifier``-role
                      gap row (the slot that replaced the transitional
                      ``method`` role at 0.3.0)
- ``full-sdp/``       multi-measurement SDP exercising row sorting across
                      binding keys (C collation: ``Zsite`` before
                      ``counts``), semicolon multi-constraints, a
                      ``value_of_dimension`` relation, a matched
                      ``statistical_modifier`` component enforced by a
                      dictionary ``statistical_modifier_iri``, gap rows, and
                      CSV quoting (comma/quote/semicolon/unicode)
- ``src/``            the scrambled input rows fed to R's writer
- ``checksums.json``  sha256 of every artifact, computed in R

THE parity contract: the Python CSV-bytes builder must reproduce R's
``readr::format_csv`` output exactly — same rows, same bytes, same sha256.
The failure-mode tests mirror metasalmon's era
``tests/testthat/test-measurement-decompositions.R``.
"""

