def load_rows(fixture):
    """The scrambled input rows R's writer was fed, as an all-string frame."""
    return pd.read_csv(
        DATA / "src" / SRC[fixture], dtype=str, keep_default_na=False
    )


def era_rows():
    """The era test table in component order (rows 0-5 = orders 1-6)."""
    rows = load_rows("era-sdp")
    rows = rows.sort_values("component_order", key=lambda s: s.astype(int))
    return rows.reset_index(drop=True)


def relation_rows():
    """The full-sdp rows, index-stable for relation mutations."""
    return load_rows("full-sdp").reset_index(drop=True)


def make_sdp(tmp_path, fixture, name="sdp"):
    """A fresh SDP with the fixture's dictionary and no semantic artifacts."""
    sdp = tmp_path / name
    (sdp / "metadata").mkdir(parents=True)
    shutil.copy(
        DATA / fixture / "metadata" / "column_dictionary.csv",
        sdp / "metadata" / "column_dictionary.csv",
    )
    return sdp


def rehash(root):
    """Recompute the manifest's sha256 after tampering with the CSV."""
    manifest_path = root / MANIFEST_REL
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    manifest["artifact"]["sha256"] = hashlib.sha256(
        (root / CSV_REL).read_bytes()
    ).hexdigest()
    manifest_path.write_bytes(
        (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode(
            "utf-8"
        )
    )


def tamper_manifest(root, mutate):
    manifest_path = root / MANIFEST_REL
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    mutate(manifest)
    manifest_path.write_bytes(
        (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode(
            "utf-8"
        )
    )


