@_REQUIRES_EXTRA
class EmlSidecarStrictnessTests(unittest.TestCase):
    """The reviewed sidecar must parse the way ``yaml::read_yaml`` parses it."""

    def _mapping_path(self, sdp: str) -> str:
        return os.path.join(sdp, "metadata", "eml-mapping.yml")

    def test_duplicate_map_key_is_refused(self):
        # R aborts with "Duplicate map key"; PyYAML silently keeps the last
        # one, so a reviewer's stray paste changed the document in only one
        # implementation, past both the parser and the schema.
        sdp = _fixture_sdp(self, "sdp-default")
        path = self._mapping_path(sdp)
        with open(path, "a", encoding="utf-8") as handle:
            handle.write("status: draft\n")

        with self.assertRaises(ValueError) as caught:
            write_eml_from_sdp(sdp, overwrite=True)
        message = str(caught.exception)
        self.assertIn("Duplicate map key", message)
        self.assertIn("status", message)

    def test_nested_duplicate_map_key_is_refused(self):
        sdp = _fixture_sdp(self, "sdp-default")
        path = self._mapping_path(sdp)
        with open(path, "a", encoding="utf-8") as handle:
            handle.write("publication:\n  public: yes\n  public: no\n")

        with self.assertRaises(ValueError) as caught:
            write_eml_from_sdp(sdp, overwrite=True)
        self.assertIn("Duplicate map key", str(caught.exception))

    def test_unquoted_publication_date_is_accepted(self):
        # R's yaml returns 2026-01-01 as the character string its validator
        # expects. PyYAML resolved it to a datetime.date, which then failed
        # the sidecar's string check -- an error R never raises.
        sdp = _fixture_sdp(self, "sdp-default")
        path = self._mapping_path(sdp)
        with open(path, encoding="utf-8") as handle:
            text = handle.read()
        self.assertIn("publication_date: '2026-01-01'", text)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(
                text.replace(
                    "publication_date: '2026-01-01'",
                    "publication_date: 2026-01-01",
                )
            )

        result = write_eml_from_sdp(sdp, overwrite=True)

        self.assertEqual(result["package_id"], _expected()["default"]["package_id"])
        self.assertEqual(
            _canonical(result["path"]),
            _canonical(os.path.join(_DATA_DIR, "eml-default.xml")),
        )

    def test_yaml_merge_keys_still_resolve(self):
        # R's yaml supports merge keys; the duplicate-key guard must not
        # mistake `<<` for a real key.
        import yaml

        loader = eml_module._strict_yaml_loader()
        merged = yaml.load(
            "base: &b\n  a: 1\nmerged:\n  <<: *b\n  c: 2\n", Loader=loader
        )
        self.assertEqual(merged["merged"], {"a": 1, "c": 2})


@_REQUIRES_EXTRA
class EmlOutputFileTests(unittest.TestCase):
    """The written document must be an ordinary file, replaced only on TRUE."""

    def test_written_eml_uses_the_umask_default_mode(self):
        # R's writeBin + file.rename leaves 0644 under a normal umask;
        # tempfile.mkstemp hard-codes 0600 and os.replace preserves it, so the
        # published metadata was unreadable to anyone but its owner. The
        # expectation is a plain write in the same directory, so the test is
        # umask-agnostic.
        sdp = _fixture_sdp(self, "sdp-default")
        result = write_eml_from_sdp(sdp, overwrite=True)

        reference = os.path.join(os.path.dirname(result["path"]), "reference.txt")
        with open(reference, "w", encoding="utf-8") as handle:
            handle.write("x")

        self.assertEqual(
            os.stat(result["path"]).st_mode & 0o777,
            os.stat(reference).st_mode & 0o777,
        )

    def test_a_bare_basename_output_path_writes_to_the_working_directory(self):
        # R's dirname("eml.xml") is "." and dir.exists(".") is TRUE, so R
        # writes into the working directory. os.path.dirname() returns ""
        # instead, and makedirs("") raised ENOENT, which the function reported
        # as "Could not create EML output directory" -- a mirror break for an
        # output path R accepts.
        sdp = _fixture_sdp(self, "sdp-default")
        workdir = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, workdir, True)
        origin = os.getcwd()
        os.chdir(workdir)
        self.addCleanup(os.chdir, origin)

        result = write_eml_from_sdp(sdp, output_path="eml.xml", overwrite=True)

        expected = os.path.realpath(os.path.join(workdir, "eml.xml"))
        self.assertEqual(result["path"], expected)
        self.assertTrue(os.path.isfile(expected))
        self.assertTrue(result["validation"])

    def test_a_relative_output_path_with_a_directory_is_still_created(self):
        # The "" -> "." normalization must not stop makedirs() from building a
        # missing relative subdirectory, which R's recursive dir.create() does.
        sdp = _fixture_sdp(self, "sdp-default")
        workdir = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, workdir, True)
        origin = os.getcwd()
        os.chdir(workdir)
        self.addCleanup(os.chdir, origin)

        result = write_eml_from_sdp(
            sdp, output_path=os.path.join("out", "nested", "eml.xml"), overwrite=True
        )

        expected = os.path.realpath(os.path.join(workdir, "out", "nested", "eml.xml"))
        self.assertEqual(result["path"], expected)
        self.assertTrue(os.path.isfile(expected))

    def test_a_truthy_non_true_overwrite_does_not_replace(self):
        # R gates on isTRUE(overwrite), so overwrite="no" must NOT authorize
        # destroying a differing document -- a truthiness test did.
        sdp = _fixture_sdp(self, "sdp-default")
        first = write_eml_from_sdp(sdp, overwrite=True)
        with open(first["path"], "a", encoding="utf-8") as handle:
            handle.write("<!-- edited -->\n")
        with open(first["path"], "rb") as handle:
            edited = handle.read()

        for value in ("no", 1, "yes", ["TRUE"]):
            with self.subTest(overwrite=value):
                with self.assertRaises(ValueError) as caught:
                    write_eml_from_sdp(sdp, overwrite=value)
                self.assertIn("set overwrite=True", str(caught.exception))
                with open(first["path"], "rb") as handle:
                    self.assertEqual(handle.read(), edited)


@_REQUIRES_EXTRA
class EmlSdpMethodTests(unittest.TestCase):
    """Method steps come from the sdp-0.3.0 placements, inside the closure.

    sdp-0.3.0 removed the methods registry: a table-constant procedure and its
    protocol live on ``tables.csv``, a dataset-wide protocol on
    ``dataset.csv``, and row-varying procedures resolve through
    ``codes.csv$term_iri``. Every vocabulary IRI the method path emits stays
    inside the reviewed closure — a table-level ``method_iri`` needs an
    accepted ledger row and a vocabulary-snapshot entry — while protocol IRIs
    are citations and are deliberately not gated. Verified against metasalmon
    main (e02111a): the placements document below matches R's method steps
    paragraph for paragraph.
    """

    def _sdp_with_legacy_registry(self, methods_rows):
        sdp = _fixture_sdp(self, "sdp-default")
        columns = (
            "dataset_id,method_iri,method_label,method_description,"
            "method_version,protocol_iri,citation"
        )
        lines = [columns] + [",".join(row) for row in methods_rows]
        with open(
            os.path.join(sdp, "metadata", "methods.csv"), "w", encoding="utf-8"
        ) as handle:
            handle.write("\n".join(lines) + "\n")
        return sdp

    def _add_table_method_to_review_closure(
        self, sdp, method_iri, method_label, table_id="counts",
        dataset_id="demo-salmon-2026",
    ):
        """Port of metasalmon's ``add_table_method_to_review_closure()``."""
        import hashlib

        from metasalmonpy.eml import _vocabulary_snapshot_sha256
        from metasalmonpy.metadata import read_sdp_csv

        vocabulary_path = os.path.join(
            sdp, "metadata", "semantic_vocabulary.csv"
        )
        vocabulary = read_sdp_csv(vocabulary_path)
        method_row = {
            "iri": method_iri,
            "label": method_label,
            "definition": "A reviewed shared-vocabulary procedure.",
            "source": "smn",
            "ontology": "smn",
            "resource_kind": "Concept",
            "type_iris": "http://www.w3.org/ns/sosa/Procedure",
            "native_type": "skos:Concept",
            "source_url": "https://w3id.org/smn/",
            "source_artifact_sha256": "3" * 64,
        }
        method_row["reviewed_snapshot_sha256"] = _vocabulary_snapshot_sha256(
            method_row
        )
        vocabulary = pd.concat(
            [vocabulary, pd.DataFrame([method_row])], ignore_index=True
        )
        vocabulary.to_csv(vocabulary_path, index=False, na_rep="")

        review_path = os.path.join(sdp, "reviewed_semantic_selections.csv")
        review = read_sdp_csv(review_path)
        review = pd.concat(
            [
                review,
                pd.DataFrame(
                    [
                        {
                            "dataset_id": dataset_id,
                            "table_id": table_id,
                            "column_name": "",
                            "target_scope": "table",
                            "target_sdp_field": "method_iri",
                            "dictionary_role": "method",
                            "decision": "accepted",
                            "confidence": "high",
                            "review_rationale": (
                                "The table-constant procedure was reviewed."
                            ),
                            "iri": method_iri,
                        }
                    ]
                ),
            ],
            ignore_index=True,
        )
        review.to_csv(review_path, index=False, na_rep="")

        mapping_path = os.path.join(sdp, "metadata", "eml-mapping.yml")
        import yaml

        with open(mapping_path, encoding="utf-8") as handle:
            mapping = yaml.safe_load(handle)
        with open(mapping_path, encoding="utf-8") as handle:
            text = handle.read()
        text = text.replace(
            mapping["semantic_vocabulary"]["sha256"],
            hashlib.sha256(Path(vocabulary_path).read_bytes()).hexdigest(),
        )
        text = text.replace(
            mapping["semantic_review"]["sha256"],
            hashlib.sha256(Path(review_path).read_bytes()).hexdigest(),
        )
        with open(mapping_path, "w", encoding="utf-8") as handle:
            handle.write(text)

    def _steps(self, path):
        document = ET.parse(path).getroot()

        def local(tag):
            return tag.split("}", 1)[1] if tag.startswith("{") else tag

        return [
            step
            for node in document.iter()
            if local(node.tag) == "methods"
            for step in node
            if local(step.tag) == "methodStep"
        ]

    def test_method_steps_come_from_tables_and_dataset_placements(self):
        from metasalmonpy.metadata import read_sdp_csv

        sdp = _fixture_sdp(self, "sdp-default")
        tables_path = os.path.join(sdp, "metadata", "tables.csv")
        tables = read_sdp_csv(tables_path)
        tables["method_iri"] = "https://example.org/methods/mark-recapture"
        tables["protocol_iri"] = "https://example.org/protocols/mark-recapture"
        tables["protocol_citation"] = (
            "Example Salmon Program. 2026. Mark-recapture protocol."
        )
        tables.to_csv(tables_path, index=False, na_rep="")
        # The emitted method IRI must be inside the review/vocabulary closure;
        # the protocol IRIs are citations and deliberately are not.
        self._add_table_method_to_review_closure(
            sdp,
            "https://example.org/methods/mark-recapture",
            "Mark-recapture estimate",
        )
        dataset_path = os.path.join(sdp, "metadata", "dataset.csv")
        dataset = read_sdp_csv(dataset_path)
        dataset["protocol_iri"] = (
            "https://example.org/protocols/monitoring-program"
        )
        dataset["protocol_citation"] = (
            "Example Salmon Program. 2026. Monitoring program protocol."
        )
        dataset.to_csv(dataset_path, index=False, na_rep="")

        result = write_eml_from_sdp(sdp, overwrite=True)

        steps = self._steps(result["path"])
        # Mapping narrative + one table placement + one dataset placement.
        self.assertEqual(len(steps), 3)
        texts = ["".join(step.itertext()) for step in steps]
        table_text = texts[1]
        dataset_text = texts[2]
        self.assertIn("Method and protocol for table 'counts'.", table_text)
        self.assertIn(
            "https://example.org/methods/mark-recapture", table_text
        )
        self.assertIn(
            "https://example.org/protocols/mark-recapture", table_text
        )
        self.assertIn("Mark-recapture protocol", table_text)
        self.assertIn("Dataset-level protocol.", dataset_text)
        self.assertIn(
            "https://example.org/protocols/monitoring-program", dataset_text
        )
        self.assertIn("Monitoring program protocol", dataset_text)

        self.assertEqual(
            list(result["methods"].columns),
            ["scope", "method_iri", "protocol_iri", "protocol_citation"],
        )
        self.assertEqual(
            list(result["methods"]["scope"]), ["counts", "dataset"]
        )
        method_iris = list(result["methods"]["method_iri"])
        self.assertEqual(
            method_iris[0], "https://example.org/methods/mark-recapture"
        )
        self.assertTrue(pd.isna(method_iris[1]) or method_iris[1] in ("", None))
        self.assertEqual(result["used_methods"], [])

