def test_rejects_blank_rows_and_comments_after_header(tmp_path):
    # An interior blank line is a blank row.
    interior = write_raw(
        tmp_path / "interior.sssom.tsv",
        sssom_text().replace("mapping_justification\n", "mapping_justification\n\n"),
    )
    with pytest.raises(ValueError, match="blank row"):
        read_sssom_mapping_set(interior)

    # Two extra trailing newlines leave a blank row behind...
    double = write_raw(tmp_path / "double.sssom.tsv", sssom_text() + "\n\n")
    with pytest.raises(ValueError, match="blank row"):
        read_sssom_mapping_set(double)

    # ...but exactly one is tolerated, mirroring R's strsplit() rule of
    # omitting a single trailing empty field.
    single = write_raw(tmp_path / "single.sssom.tsv", sssom_text() + "\n")
    assert len(read_sssom_mapping_set(single).mappings) == 1

    commented = write_raw(
        tmp_path / "comment.sssom.tsv", sssom_text() + "# stray comment\n"
    )
    with pytest.raises(ValueError, match="before the TSV header"):
        read_sssom_mapping_set(commented)


