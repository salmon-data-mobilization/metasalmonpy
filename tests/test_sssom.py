"""SSSOM 1.1 support tests (metasalmon 0.1.7 replay, S10 chunk 1).

Byte-parity fixtures under ``tests/data/sssom/`` were generated by running
metasalmon's R implementation (``R/sssom.R``, the spec) directly:

- ``src/``            source mapping sets (unsorted curie maps, scrambled
                       column order, unsorted rows, non-ASCII text)
- ``canonical/``      R's ``.ms_sssom_canonical_bytes`` output for each source
- ``r-sdp/``          an SDP written by R's ``write_sdp_sssom`` over all three
- ``checksums.json``  sha256 of every fixture, computed in R

THE parity contract: the Python canonical-bytes builder must reproduce R's
bytes exactly — same mapping set, same sha256. The failure-mode tests mirror
metasalmon's ``tests/testthat/test-sssom.R``.
"""

import hashlib
import json
import unittest
from pathlib import Path

import pytest

try:
    import pandas as pd
except ImportError:  # pragma: no cover
    pd = None

if pd is None:
    raise unittest.SkipTest("pandas not installed")

import metasalmonpy
from metasalmonpy import sssom
from metasalmonpy.sssom import (
    SssomMappingSet,
    read_sssom_mapping_set,
    validate_sdp_sssom,
    write_sdp_sssom,
)

DATA = Path(__file__).parent / "data" / "sssom"
CHECKSUMS = json.loads((DATA / "checksums.json").read_text(encoding="utf-8"))
FIXTURES = ("psc-to-gcdfo.sssom.tsv", "multi-sort.sssom.tsv", "gaps.sssom.tsv")


def sssom_text(
    mapping_set_id="https://example.org/mappings/psc-to-gcdfo",
    mapping_set_version="2026-07-31",
    object_source="https://w3id.org/gcdfo/salmon",
    object_source_version="0.0.8",
    rows=None,
    extra_prefixes=(),
    extra_metadata=(),
):
    """Mirror of the R test helper ``sssom_test_text``."""
    if rows is None:
        rows = [
            "\t".join(
                (
                    "psc:PSC-CV-000001",
                    "Net",
                    "skos:exactMatch",
                    "gcdfo:FixedSiteCensusManual",
                    "Fixed Site Census (Manual)",
                    "semapv:ManualMappingCuration",
                )
            )
        ]
    prefixes = [
        "#   psc: https://w3id.org/psc/vocab/concept/",
        "#   gcdfo: https://w3id.org/gcdfo/salmon#",
        "#   skos: http://www.w3.org/2004/02/skos/core#",
        "#   semapv: https://w3id.org/semapv/vocab/",
        "#   sssom: https://w3id.org/sssom/",
        *extra_prefixes,
    ]
    lines = [
        "# sssom_version: 1.1",
        f"# mapping_set_id: {mapping_set_id}",
        f"# mapping_set_version: {mapping_set_version}",
        "# license: https://creativecommons.org/licenses/by/4.0/",
        "# subject_source: https://w3id.org/psc/vocab/",
        "# subject_source_version: v0.2.0",
        f"# object_source: {object_source}",
        f"# object_source_version: {object_source_version}",
        *extra_metadata,
        "# curie_map:",
        *prefixes,
        "\t".join(
            (
                "subject_id",
                "subject_label",
                "predicate_id",
                "object_id",
                "object_label",
                "mapping_justification",
            )
        ),
        *rows,
    ]
    return "\n".join(lines) + "\n"


def write_raw(path, text):
    Path(path).write_bytes(text.encode("utf-8"))
    return Path(path)


# --- byte parity against the R implementation --------------------------------


@pytest.mark.parametrize("name", FIXTURES)
def test_canonical_bytes_match_r_exactly(name):
    mapping_set = read_sssom_mapping_set(DATA / "src" / name)
    got = sssom._canonical_bytes(mapping_set)
    assert hashlib.sha256(got).hexdigest() == CHECKSUMS["canonical"][name]
    assert got == (DATA / "canonical" / name).read_bytes()


@pytest.mark.parametrize("name", FIXTURES)
def test_canonical_bytes_are_idempotent(name):
    canonical_path = DATA / "canonical" / name
    reread = read_sssom_mapping_set(canonical_path)
    assert sssom._canonical_bytes(reread) == canonical_path.read_bytes()


def test_reader_accepts_r_fixture_and_parses_metadata():
    result = read_sssom_mapping_set(DATA / "src" / "psc-to-gcdfo.sssom.tsv")
    assert isinstance(result, SssomMappingSet)
    assert result.metadata["sssom_version"] == "1.1"
    assert (
        result.metadata["curie_map"]["psc"]
        == "https://w3id.org/psc/vocab/concept/"
    )
    assert list(result.metadata["curie_map"]) == sorted(
        result.metadata["curie_map"]
    )
    assert len(result.mappings) == 1
    assert result.mappings["predicate_id"].tolist() == ["skos:exactMatch"]
    assert validate_sdp_sssom(DATA / "src" / "psc-to-gcdfo.sssom.tsv") is True


def test_unsorted_input_normalizes_to_sorted_canonical_output():
    mapping_set = read_sssom_mapping_set(DATA / "src" / "multi-sort.sssom.tsv")
    text = sssom._canonical_bytes(mapping_set).decode("utf-8")
    lines = text.split("\n")
    curie_lines = [line for line in lines if line.startswith("#   ")]
    assert [line.split(":")[0].strip("# ") for line in curie_lines] == [
        "SDO",
        "gcdfo",
        "psc",
        "semapv",
        "skos",
        "sssom",
    ]
    header = next(line for line in lines if line.startswith("subject_id"))
    # Scrambled source columns come back in the canonical column order.
    assert header.split("\t") == [
        "subject_id",
        "subject_label",
        "predicate_id",
        "object_id",
        "object_label",
        "mapping_justification",
        "mapping_cardinality",
        "confidence",
        "comment",
    ]
    data_rows = lines[lines.index(header) + 1 : -1]
    keys = [tuple(row.split("\t")) for row in data_rows]
    assert keys == sorted(keys)
    # Tie on subject_id resolved by the next canonical column that differs.
    assert data_rows[0].split("\t")[2] == "skos:broadMatch"
    assert data_rows[1].split("\t")[2] == "skos:exactMatch"


def test_python_validates_r_written_sdp():
    assert validate_sdp_sssom(DATA / "r-sdp") is True


def test_python_writer_reproduces_r_sdp_mapping_set_bytes(tmp_path):
    sdp = tmp_path / "sdp"
    sdp.mkdir()
    manifest_path = write_sdp_sssom(
        sdp, mapping_sets=[DATA / "src" / name for name in FIXTURES]
    )
    assert manifest_path == str(sdp / "metadata" / "semantic" / "mapping-sets.json")

    for name in FIXTURES:
        written = (sdp / "metadata" / "semantic" / name).read_bytes()
        assert (
            hashlib.sha256(written).hexdigest()
            == CHECKSUMS["r_sdp_semantic"][name]
        )
        assert written == (
            DATA / "r-sdp" / "metadata" / "semantic" / name
        ).read_bytes()

    # Manifest parity is contract-level: identical mapping-set entries (paths,
    # hashes, row counts, metadata), honest per-implementation provenance.
    ours = json.loads(Path(manifest_path).read_text(encoding="utf-8"))
    theirs = json.loads(
        (DATA / "r-sdp" / "metadata" / "semantic" / "mapping-sets.json").read_text(
            encoding="utf-8"
        )
    )
    assert ours["schema_version"] == theirs["schema_version"] == "1.0"
    assert ours["sssom_version"] == theirs["sssom_version"] == "1.1"
    assert ours["mapping_sets"] == theirs["mapping_sets"]
    assert ours["provenance"]["generated_by"] == "metasalmonpy.write_sdp_sssom"
    assert theirs["provenance"]["generated_by"] == "metasalmon::write_sdp_sssom"


def test_writer_is_deterministic_across_input_order(tmp_path):
    first, second = tmp_path / "first", tmp_path / "second"
    first.mkdir()
    second.mkdir()
    paths = [DATA / "src" / name for name in FIXTURES]
    write_sdp_sssom(first, mapping_sets=paths)
    write_sdp_sssom(second, mapping_sets=list(reversed(paths)))
    first_files = sorted(p.name for p in (first / "metadata" / "semantic").iterdir())
    second_files = sorted(p.name for p in (second / "metadata" / "semantic").iterdir())
    assert first_files == second_files
    for name in first_files:
        assert (first / "metadata" / "semantic" / name).read_bytes() == (
            second / "metadata" / "semantic" / name
        ).read_bytes()
    manifest = json.loads(
        (first / "metadata" / "semantic" / "mapping-sets.json").read_text(
            encoding="utf-8"
        )
    )
    # Asserting `ids == sorted(ids)` would only prove Python agrees with
    # Python. The expectation is the order R wrote into the fixture SDP.
    r_manifest = json.loads(
        (DATA / "r-sdp" / "metadata" / "semantic" / "mapping-sets.json").read_text(
            encoding="utf-8"
        )
    )
    expected_ids = [entry["mapping_set_id"] for entry in r_manifest["mapping_sets"]]
    assert expected_ids == [
        "https://example.org/mappings/multi-sort",
        "https://example.org/mappings/psc-to-gcdfo",
        "https://example.org/mappings/psc-to-sdo-gaps",
    ]
    assert [
        entry["mapping_set_id"] for entry in manifest["mapping_sets"]
    ] == expected_ids


