def test_yaml_subset_quoting_and_comments_match_r(tmp_path):
    # Both behaviours verified against R's reader: single-quoted scalars are
    # accepted, and a whitespace-preceded '#' ends a plain scalar while a
    # glued '#' (IRI fragment) does not.
    quoted = sssom_text().replace(
        "# mapping_set_version: 2026-07-31",
        "# mapping_set_version: '2026-07-31'",
    )
    path = write_raw(tmp_path / "quoted.sssom.tsv", quoted)
    assert (
        read_sssom_mapping_set(path).metadata["mapping_set_version"]
        == "2026-07-31"
    )

    commented = sssom_text().replace(
        "# mapping_set_version: 2026-07-31",
        "# mapping_set_version: 2026-07-31 # reviewed",
    )
    path = write_raw(tmp_path / "commented.sssom.tsv", commented)
    result = read_sssom_mapping_set(path)
    assert result.metadata["mapping_set_version"] == "2026-07-31"
    assert result.metadata["curie_map"]["gcdfo"] == "https://w3id.org/gcdfo/salmon#"


